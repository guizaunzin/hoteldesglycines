export function lookup(word: string, sentence = ""): string | null {
  const w = normalize(word).replace(/[«»"!?.,;:()]/g, "").trim();
  if (!w) return null;
  // expressions de plusieurs mots présentes dans la phrase
  const ns = normalize(sentence);
  for (const key of Object.keys(ENTRIES)) {
    if (key.includes(" ") && key.split(" ").includes(w) && ns.includes(key)) return `${key} — ${ENTRIES[key]}`;
  }
  const candidates = [w, w.replace(/s$/, ""), w.replace(/e$/, ""), w.replace(/es$/, ""), w.replace(/ee?s?$/, "e")];
  for (const c of candidates) if (ENTRIES[c]) return ENTRIES[c];
  return null;
}
